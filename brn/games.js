function getGameCategory(game) {
  if (game && typeof game.category === "string" && CATEGORY_LABELS[game.category]) {
    return game.category;
  }

  if (game && GAME_CATEGORY_OVERRIDES[game.label]) {
    return GAME_CATEGORY_OVERRIDES[game.label];
  }

  const text = `${game.label} ${game.url}`.toLowerCase();
  for (const rule of CATEGORY_RULES) {
    if (rule.patterns.some((pattern) => pattern.test(text))) {
      return rule.category;
    }
  }
  return "arcade";
}

const categorizedGames = games.map((game) => ({
  ...game,
  category: game.category || GAME_CATEGORY_OVERRIDES[game.label] || getGameCategory(game)
}));

const sortedGames = [...categorizedGames].sort((a, b) =>
  a.label.localeCompare(b.label, undefined, {
    numeric: true,
    sensitivity: "base"
  })
);

